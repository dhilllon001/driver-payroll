function methodLines(
  picks: { methodId: string; single: number; team?: number }[],
): PayrollSchedule['methods'] {
  return picks.map((p, i) => {
    const m = METHODS.find((x) => x.id === p.methodId)!;
    return {
      id: `sml-${p.methodId}-${i}`,
      methodId: m.id,
      methodName: m.name,
      basedOn: m.basedOn,
      singleRate: p.single,
      teamRate: p.team ?? p.single,
    };
  });
}

